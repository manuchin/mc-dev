export const LANGS = ["es", "en", "pt"];

export function detectLang() {
  try {
    const saved = localStorage.getItem("mc-lang");
    if (saved && LANGS.indexOf(saved) !== -1) return saved;
  } catch (e) { /* sin localStorage */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "es";
  const two = String(nav).slice(0, 2).toLowerCase();
  return LANGS.indexOf(two) !== -1 ? two : "es";
}
